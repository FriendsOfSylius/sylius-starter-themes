<?php

declare(strict_types=1);

namespace App\Themes;

use Sylius\Bundle\ThemeBundle\Context\ThemeContextInterface;
use Sylius\TwigHooks\Hook\Renderer\HookRendererInterface;
use Symfony\Component\DependencyInjection\Attribute\AsDecorator;
use Symfony\Component\DependencyInjection\Attribute\AutowireDecorated;

/**
 * Renders the hooks of the theme of the current channel.
 *
 * Themes installed with the theme-bundle target prefix their hook names with "<theme>:"
 * ("cellar:sylius_shop.homepage.index"), so their hookables only apply to the channels
 * using that theme. Before each hook name, this adds its prefixed version: Twig Hooks
 * merges the hookables of every name, the first one winning, so the theme overrides or
 * disables the hookables of the app.
 *
 * Generated by sylius-starter/themes: do not edit.
 */
#[AsDecorator('sylius_twig_hooks.renderer.hook')]
final readonly class ThemeHookRenderer implements HookRendererInterface
{
    /** Not "#", which Twig Hooks reads as a section separator in prefixes. */
    public const SEPARATOR = ':';

    public function __construct(
        #[AutowireDecorated]
        private HookRendererInterface $inner,
        private ThemeContextInterface $themeContext,
    ) {}

    public function render(array $hookNames, array $hookContext = []): string
    {
        $theme = $this->themeContext->getTheme();

        if (null === $theme) {
            return $this->inner->render($hookNames, $hookContext);
        }

        $prefix = self::prefix($theme->getName());
        $themedHookNames = [];

        foreach ($hookNames as $hookName) {
            // Nested hooks inherit the prefixed names of their parent through the Twig Hooks prefixes.
            if (!str_starts_with($hookName, $prefix)) {
                $themedHookNames[] = $prefix . $hookName;
            }

            $themedHookNames[] = $hookName;
        }

        return $this->inner->render(array_values(array_unique($themedHookNames)), $hookContext);
    }

    /** "sylius-starter/cellar" => "cellar:" */
    public static function prefix(string $themeName): string
    {
        $position = strrpos($themeName, '/');

        return (false === $position ? $themeName : substr($themeName, $position + 1)) . self::SEPARATOR;
    }
}
